void
CTextMT::put(int _iXPos,int _iYPos,DWORD _dwColor,char *_lpStr,int _iAlpha)
{

	char *strOutputText	=	w2j((BYTE *)_lpStr);

	if (_iAlpha	<=	0)	return;
	_iAlpha	=	min(_iAlpha,32);

	if(m_isShadow	&&	_iAlpha	==	32)
		putHB(_iXPos+m_posShadowMargin.x,_iYPos+m_posShadowMargin.y,m_dwShadowColor,strOutputText);

	if (_iAlpha	==	32)
	{
		putNormal(_iXPos,_iYPos,_dwColor,strOutputText);
		return;
	}

	if (_iAlpha	==	16)
	{
		putHB(_iXPos,_iYPos,_dwColor,strOutputText);
		return;
	}

	putAB(_iXPos,_iYPos,_dwColor,strOutputText,_iAlpha);
}

void
CTextMT::cPut(int _iXPos,int _iYPos,DWORD _dwColor,char *_lpStr,int _iAlpha)
{
	_iXPos	-=	strlen(_lpStr)*m_iFontWidth/2;

	put(_iXPos,_iYPos,_dwColor,_lpStr,_iAlpha);
}


