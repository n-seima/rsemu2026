//	xs를 기준으로 해서 line번째의 문장을 리턴한다.
//
char *
CTextMT::getLine(int _iWidth,int line,char *_lpString)
{
	static	char	text[1024];

	BYTE	fstByte,secondByte;
	int		x=0,iCharSize=0,index=0,iTextPos=0,iLineWidth=_iWidth/m_iFontWidth;

	while(*_lpString)
	{	fstByte		= *_lpString++;

		if (fstByte & 0x80)	iCharSize	=	m_iFontWidth*2;
		else				iCharSize	=	m_iFontWidth;

		if(x + iCharSize > _iWidth)			//	가로 사이즈가 넘어 갔다.
		{	x	=	0;

			if (index == line)
			{	text[iTextPos]	=	NULL;

				iTextPos--;

				if (iTextPos < iLineWidth-1)		//	한글이 반으로 나뉜경우..
				{	iTextPos++;
					text[iTextPos+1]	=	NULL;
					text[iTextPos  ]	=	32;
				}

				if (text[iTextPos]==32)
				{	int beginPos=0,space=0,endPos=0,i;

					for (i=iTextPos;i>=0;i--)
					{	
						if (text[i]	==	32)	space++;
						else
						{	endPos	=	i;
							i		=	0;
						}
					}

					for (i=0;i<iTextPos;i++)
						if (text[i] == 32 && text[i+1] != 32)	beginPos = i+1;

					if (beginPos!=0 && endPos!=0 && space!=iLineWidth)
					{	char	temp[1024];

						memcpy(temp					,&text[beginPos],endPos-beginPos+1);
						memcpy(&text[beginPos+space],temp			,endPos-beginPos+1);

						for (i=beginPos;i<beginPos+space;i++)		text[i]	=	32;
					}
				}

				return text;
			}

			iTextPos	=	0;
			index++;

			while(_lpString)
			{	if (fstByte!=32) break;
				fstByte	= *_lpString++;
				if (_lpString==NULL || fstByte==NULL)	return	NULL;
			}
		}

		if(fstByte == 0x0d || fstByte == 0x0a)					//	캐리지 리턴이다.
		{	if (index == line)
			{	if (iTextPos==0)	text[iTextPos++]=32;
				text[iTextPos]	=	NULL;

				return text;
			}

			if (fstByte == 0x0d)	if (*_lpString == 0x0a)	*_lpString++;

			index++;
			iTextPos	=	0;
			x		=	0;
		}
		else
		if(fstByte & 0x80)    // 한글
		{	secondByte	=	*_lpString++;

			text[iTextPos++]	=	fstByte;
			text[iTextPos++]	=	secondByte;

			x				+= m_iFontWidth*2;
		}
		else
		{	text[iTextPos++]	=	fstByte;

			x				+=	m_iFontWidth;
		}
	}

	if (index == line)
	{	text[iTextPos]	=	NULL;
		return text;
	}

	return NULL;
}	//	CText::getLine(int _iWidth,int line,char *_lpString)

int
CTextMT::getLineCount(int _iWidth,char *_lpString)
{
	int iCount = 0;

	while(1)
	{	char *lpString	=	getLine(_iWidth,iCount,_lpString);

		if (!lpString) return iCount;

		iCount++;
	}

	return iCount;
}

//
//	_lpString을 _iWidth,_iHeight에 맞춰 찍는다.
//
void
CTextMT::fitPut(int _iXPos,int _iYPos,int _iWidth,int _iHeight,DWORD _dwColor,char *_lpString,int _iBase,int _iAlpha)
{	
	int		iLineCount	=	_iHeight/(m_iFontHeight+2);

	for (int i=_iBase;i<iLineCount+_iBase;i++)
	{
		char *lpText	=	getLine(_iWidth,i,_lpString);

		if (!lpText) return;

		put(_iXPos,_iYPos,_dwColor,lpText,_iAlpha);

		_iYPos	+=	m_iFontHeight+2;
	}
}	//	CTextMT::fitPut(int _iXPos,int _iYPos,int _iWidth,int _iHeight,WORD wColor,char *_lpString,int _iBase,int _iAlpha)


//
//	이중포인터에서 _iLine번째 문장을 얻어 온다.
//
char *
CTextMT::getLine(int _iWidth,int _iLine,char **_lpStrings)
{	
	int iCurText	=	0,iTotalLine	=	0;

	while(1)
	{	if (strcmp(_lpStrings[iCurText],"")	==	0)	return NULL;

		int	iLineCount	=	getLineCount(_iWidth,_lpStrings[iCurText]);

		if (iTotalLine+iLineCount > _iLine)
			return getLine(_iWidth,_iLine-iTotalLine,_lpStrings[iCurText]);

		iTotalLine		+=	iLineCount;

		iCurText++;
	}

	return NULL;
}	//	CText::getLine(int xs,int line,char **pStr)

//
//	이중포인터의 문장을 받아 몇라인으로 되어 있는지 얻어 온다.
//
int
CTextMT::getLineCount(int _iWidth,char **_lpStrings)
{
	int iCurText	=	0,iTotalLine	=	0;

	while(1)
	{	iTotalLine	+=	getLineCount(_iWidth,_lpStrings[iCurText++]);

		if(strcmp(_lpStrings[iCurText],"")==0)	return iTotalLine;
	}

	return 0;
}	//	CTextMT::getLineCount(int _iWidth,char **_lpStrings)


//
//	이중포인터의 문장을 받아 출력 한다.
//
void
CTextMT::fitPut(int _iXPos,int _iYPos,int _iWidth,int _iHeight,DWORD _dwColor,char **_lpStrings,int _iBase,int _iAlpha)
{	int	iLineCount	=	_iHeight/(m_iFontHeight+2);

	for (int i=_iBase;i<iLineCount+_iBase;i++)
	{	char *lpText=	getLine(_iWidth,i,_lpStrings);

		if (!lpText) return;

		put(_iXPos,_iYPos,_dwColor,lpText);

		_iYPos	+=	m_iFontHeight+2;
	}
}	//	CTextMT::fitPut(int _iXPos,int _iYPos,int _iWidth,int _iHeight,WORD wColor,char **_lpStrings,int _iBase,int _iAlpha)