inline	char*
CTextMT::w2j(BYTE *_lpString)
{
	static	BYTE	s_strJohap[1024];

	int iIndex=0,iFirst,iSecond;

	while(_lpString[iIndex])
	{	if (_lpString[iIndex]<0x80)
		{	s_strJohap[iIndex]	=	_lpString[iIndex];
			iIndex++;
		}
		else
		{
			iFirst				=	_lpString[iIndex  ]-0xb0;
			iSecond				=	_lpString[iIndex+1]-0xa1;

			s_strJohap[iIndex  ]=	c_aJohapCode[iFirst*94*2+iSecond*2  ];
			s_strJohap[iIndex+1]=	c_aJohapCode[iFirst*94*2+iSecond*2+1];

			if ((s_strJohap[iIndex+1]&0x1f)==1) 	s_strJohap[iIndex+1]--;

			iIndex				+=	2;
		}
	}

	s_strJohap[iIndex]	=	NULL;

	return	(char*)s_strJohap;
}	//	CTextMT::w2j(BYTE *String)


BOOL
CTextMT::selectFont(int _iSelectFont)
{
	if	(_iSelectFont	>=	dFONT_COUNT				)	return FALSE;
	if	(!s_aFont[_iSelectFont].isLoadedSpriteFont())	return FALSE;

//	m_iFontWidth		=	s_aFont[_iSelectFont].getFontWidth();
//	m_iFontHeight		=	s_aFont[_iSelectFont].getFontHeight();
	m_lpHangulBuffer=	s_aFont[_iSelectFont].getHangulBuffer();
	m_lpHangulOffset=	s_aFont[_iSelectFont].getHangulOffset();
	m_lpEnglishBuffer=	s_aFont[_iSelectFont].getEnglishBuffer();
	m_lpEnglishOffset=	s_aFont[_iSelectFont].getEnglishOffset();

	return	TRUE;
}

void
CTextMT::putNormal(int _iXPos,int _iYPos,DWORD _dwColor,char *_lpString)
{
	int	iFirst;

	WORD	wColor	=	RGB24To16(_dwColor);

	while(*_lpString)
	{	iFirst = *_lpString++;

		if(iFirst & 0x80)    // 한글
		{
			tuHangul	h;
			int			b1, b2, b3, first=0, mid=0, last=0;

			h.hchar.fstchar = iFirst;
			h.hchar.sndchar = *_lpString++;

			//0x7c00;0x3e0;0x1f
			first = *(*(INDEXHF)+h.hcode.chosung);		//	초성
			mid   = *(*(INDEXHF+1)+h.hcode.jungsung);	//	중성
			last  = *(*(INDEXHF+2)+h.hcode.jongsung);	//	종성

			if(!last)	//	종성이 없다.
			{	b1		= *(*(REFFIRST8)+mid);
				b2		= *(*(REFSECOND10_8)+first);

				cDRAW::PutFont(_iXPos,_iYPos,wColor,&m_lpHangulBuffer[m_lpHangulOffset[b1*20 + first    ]]);			//	초성

				if (mid) cDRAW::PutFont(_iXPos,_iYPos,wColor,&m_lpHangulBuffer[m_lpHangulOffset[160 + b2*22 + mid]]);	//	중성
			}
			else
			{	b1		= *(*(REFFIRST8+1)+mid);
				b2		= *(*(REFSECOND10_8+1)+first);
				b3		=   *(REFLAST10_8+mid);

				cDRAW::PutFont(_iXPos,_iYPos,wColor,&m_lpHangulBuffer[m_lpHangulOffset[b1*20 + first     ]]);	//	초성
				cDRAW::PutFont(_iXPos,_iYPos,wColor,&m_lpHangulBuffer[m_lpHangulOffset[160 + b2*22 + mid ]]);	//	중성
				cDRAW::PutFont(_iXPos,_iYPos,wColor,&m_lpHangulBuffer[m_lpHangulOffset[248 + b3*28 + last]]);	//	종성
			}

			_iXPos += m_iFontWidth*2;
		}
		else
		{	if(iFirst != ' ') // 영어
				cDRAW::PutFont(_iXPos,_iYPos,wColor,m_lpEnglishBuffer+m_lpEnglishOffset[iFirst]);

			_iXPos	+= m_iFontWidth;
		}
	}
}

