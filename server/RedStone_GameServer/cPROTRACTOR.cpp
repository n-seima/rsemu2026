int
cPROTRACTOR::getAngleToTarget(int nX,int nY,int nTargetX,int nTargetY,BOOL _bIsOval)
{	
	int	nAngle;
	int	nDeltaX = nTargetX - nX;
	int nDeltaY = (nTargetY - nY)<<_bIsOval;

	if ( nDeltaX == 0 ) 
	{	if ( nDeltaY > 0 ) return 270;
		if ( nDeltaY < 0 ) return 90;
	}

	if ( nDeltaY == 0 ) 
	{	if ( nDeltaX > 0 ) return 0;
		if ( nDeltaX < 0 ) return 180;
	}

	if ( nDeltaX == 0 && nDeltaY == 0 )
		return 0;

	if ( nDeltaY < nDeltaX ) 
	{	if ( -nDeltaY < nDeltaX )
				nAngle = ANGLE_000 + c_aArcTanTbl[MAX_ANGLE_DEGREE + ( MAX_ANGLE_DEGREE * nDeltaY / nDeltaX )];
		else	nAngle = ANGLE_270 - c_aArcTanTbl[MAX_ANGLE_DEGREE + ( MAX_ANGLE_DEGREE * nDeltaX / nDeltaY )];
	} 
	else 
	{	if ( -nDeltaY < nDeltaX )
				nAngle = ANGLE_090 - c_aArcTanTbl[MAX_ANGLE_DEGREE + ( MAX_ANGLE_DEGREE * nDeltaX / nDeltaY )];
		else	nAngle = ANGLE_180 + c_aArcTanTbl[MAX_ANGLE_DEGREE + ( MAX_ANGLE_DEGREE * nDeltaY / nDeltaX )];
	}

	// INVERT angle...
	nAngle = MAX_ANGLE_DEGREE - nAngle;
	// CLIP angle...
			if ( nAngle < 0					) 	nAngle += MAX_ANGLE_DEGREE;
	else	if ( nAngle >= MAX_ANGLE_DEGREE )	nAngle -= MAX_ANGLE_DEGREE;

	return A1024TO360(nAngle);
}

//
//	패스를 만든다.
void
cPROTRACTOR::getPath(cPath *_lpPath,int _iBeginX,int _iBeginY,int _iDestX,int _iDestY,int _iDistance)
{
	int		iAngle			=	getAngleToTarget(_iBeginX,_iBeginY,_iDestX,_iDestY);

	int		xs				=	((_iDistance*c_aOvalRevised[iAngle].x)>>8);
	int		ys				=	((_iDistance*c_aOvalRevised[iAngle].y)>>9);
	int		tapX			=	xs/dUPDATE_MOVE_POS_PERIOD;
	int		tapY			=	ys/dUPDATE_MOVE_POS_PERIOD;
	int		revisedNumberX	=	xs-(tapX*dUPDATE_MOVE_POS_PERIOD);
	int		revisedNumberY	=	ys-(tapY*dUPDATE_MOVE_POS_PERIOD);
	int		i;

	if (revisedNumberX	<	0)
		revisedNumberX	=	-revisedNumberX;
	if (revisedNumberY	<	0)
		revisedNumberY	=	-revisedNumberY;

	//	롤 오버... 조금이라도 빠르게 하려고 해 봤다.
	for (i=dUPDATE_MOVE_POS_PERIOD;i;i--)
	{
		_lpPath[i-1].x=tapX;
		_lpPath[i-1].y=tapY;
	}

	iAngle	/=	90;

	for (i=0;i<revisedNumberX;i++)
		_lpPath[(i*dUPDATE_MOVE_POS_PERIOD)/revisedNumberX].x+=c_aAddOval[0][iAngle];
	for (i=0;i<revisedNumberY;i++)
		_lpPath[(i*dUPDATE_MOVE_POS_PERIOD)/revisedNumberY].y+=c_aAddOval[1][iAngle];
}

//
//	_iX1,_iY1에서 _iX2,_iY2까지 픽셸 단위로 길을 찾는다.
int
cPROTRACTOR::getLine(int _iX1,int _iY1,int _iX2,int _iY2,cPOINT *_lpRoad,int _iTerm,int _iSize)
{
	// 기울기값
	int	i;
	int	iRoadCount	=	0;		//	경유하는 포인트의 수
	int	iWidth,iHeight,iDx,iDy;

    if	(_iX1 > _iX2)
		iWidth	=	_iX1	-	_iX2,iDx		=	-1;
	else
		iWidth	=	_iX2	-	_iX1,iDx		=	1;

    if	(_iY1 > _iY2)
		iHeight	=	_iY1	-	_iY2,iDy		=	-1;
	else
		iHeight	=	_iY2	-	_iY1,iDy		=	1;

	int		dPr,dPru,P;

	_lpRoad[0].x	=	_iX1;
	_lpRoad[0].y	=	_iY1;
	iRoadCount		=	1;

	if	(_iX2	==	_iX1)
	{
		for (i=0;i<iHeight;i++)
		{
			if	((i%_iTerm)	==	0)
			{
				_lpRoad[iRoadCount].x	=	_iX1;
				_lpRoad[iRoadCount].y	=	_iY1;
				iRoadCount++;

				if (iRoadCount	>=	_iSize)
					return	-1;
			}
			_iY1	+=	iDy;
		}

		return iRoadCount;
	}

	if	(_iY2 == _iY1)
	{
		for (i=0;i<iWidth;i++)
		{
			if ((i%_iTerm)	==	0)
			{
				_lpRoad[iRoadCount].x	=	_iX1;
				_lpRoad[iRoadCount].y	=	_iY1;
				iRoadCount++;

				if (iRoadCount	>=	_iSize)
					return	-1;
			}
			_iX1	+=	iDx;
		}

		return iRoadCount;
	}

    if	(iWidth >= iHeight)
    {           
        dPr 	= iHeight<<1;   						// amount to increment decision if right is chosen (always)
        dPru 	= dPr - (iWidth<<1);				// amount to increment decision if up is chosen
        P 		= dPr - iWidth;						// decision variable start value
        
        for (; iWidth>=0; iWidth--)						// process each point in the line one at a time (just use iWidth)
        {
			if	((iWidth % _iTerm)	==	0)
			{
				_lpRoad[iRoadCount].x	=	_iX1;
				_lpRoad[iRoadCount].y	=	_iY1;
				iRoadCount++;

				if	(iRoadCount	>=	_iSize)
					return	-1;
			}

            if (P > 0)                              // is the pixel going right AND up?
            {
				_iX1	+=iDx;					// increment independent variable
                _iY1	+=iDy; 					// increment dependent variable
                P	+=dPru;						// increment decision (for up)
            }
            else									// is the pixel just going right?
            {   _iX1	+=iDx;					// increment independent variable
                P	+=dPr;						// increment decision (for right)
            }
        }
    }
    else
    {
        dPr 	= iWidth<<1;   							// amount to increment decision if right is chosen (always)
        dPru 	= dPr - (iHeight<<1);    				// amount to increment decision if up is chosen
        P 		= dPr - iHeight;							// decision variable start value
        
        for (; iHeight>=0; iHeight--)							// process each point in the line one at a time (just use iHeight)
        {
			if ((iHeight % _iTerm)	==	0)
			{
				_lpRoad[iRoadCount].x	=	_iX1;
				_lpRoad[iRoadCount].y	=	_iY1;
				iRoadCount++;

				if (iRoadCount	>=	_iSize)
					return	-1;
			}

            if (P > 0)                              // is the pixel going up AND right?
            { 
                _iX1	+=iDx; 					// increment dependent variable
                _iY1	+=iDy;					// increment independent variable
                P	+=dPru;						// increment decision (for up)
            }
            else									// is the pixel just going up?
            {
                _iY1	+=iDy;					// increment independent variable
                P	+=dPr;						// increment decision (for right)
            }
        }		
   }		

	return	iRoadCount;
}

