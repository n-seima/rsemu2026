class	cPROTRACTOR
{
public:
	int				getAngleToTarget(int nX,int nY,int nTargetX,int nTargetY,BOOL _bIsOval=TRUE);
	inline	void	getAnglePos(cPOINT	*_lpPos,int _iAngle,int _iDist,BOOL _bIsOval=TRUE)
	{
		int	xs	=	((_iDist*c_aOvalRevised[_iAngle].x)>>8);
		int	ys	=	((_iDist*c_aOvalRevised[_iAngle].y)>>(8+_bIsOval));

		_lpPos->x	+=	xs;
		_lpPos->y	+=	ys;
	}

	inline	void	getTargetPos(cPOINT	*_lpPos,int _iTargetPosX,int _iTargetPosY,int _iDistance,BOOL _bIsOval=TRUE)
	{
		int	iAngle	=	getAngleToTarget(_lpPos->x,_lpPos->y,_iTargetPosX,_iTargetPosY,_bIsOval);

		getAnglePos(_lpPos,iAngle,_iDistance,_bIsOval);
	}


	int				getLine(int _iX1,int _iY1,int _iX2,int _iY2,cPOINT *_lpRoad,int _iTerm,int _iSize);
	int				getLine(int _iX1,int _iY1,int _iX2,int _iY2,cPOINT *_lpRoad,int _iSize);
	int				getMapLine(int _iX1,int _iY1,int _iX2,int _iY2,cPOINT *_lpRoad,int _iSize);

	void			getPath(cPath	*_lpPaths,int _iBeginX,int _iBeginY,int _iDestX,int _iDestY,int _iDistance);
};

