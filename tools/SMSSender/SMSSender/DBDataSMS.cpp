BOOL cDBDataSMS::sendSMS(TCHAR *_pszRecvPhone, TCHAR *_pszSendPhone, TCHAR *_pszContent)
{
	// 데이타 넣기
	int iCurDBIdx;
	TCHAR szSQL[512];
	if((iCurDBIdx = m_DB.getRestDBConnect()) == cAdoDB::eERRORRESTDBCONNECT){	// 내부적으로 CS 처리, 현재 놀고있는 Connect 인덱스를 리턴하고 리턴한 인덱스는 Lock
		// 놀고 있는 dbConnect 가 없을 경우 Error 처리
		return FALSE;	
	}	
	_stprintf_s(szSQL, _countof(szSQL), 
			_T("Insert into em_tran(\
					tran_phone, tran_callback, tran_status, tran_date, tran_msg\
				)values(\
					'%s', '%s', '1', getdate(),  '%s')"), 
				_pszRecvPhone, _pszSendPhone, _pszContent);
	if(!m_DB.execSql(iCurDBIdx, szSQL, _T(__FUNCTION__), __LINE__)){
		return FALSE;
	}
	m_DB.clearData(iCurDBIdx);

	return TRUE;
}