///////////////////////////////////////////////////////////////////////////////////////////////////////////
// Name : 
// Desc : 
///////////////////////////////////////////////////////////////////////////////////////////////////////////
cTrayIcon::cTrayIcon()
{
	memset(&m_tnd, 0, sizeof(m_tnd));
	m_bStopAnimation = FALSE;
	m_hThread = NULL;
}


///////////////////////////////////////////////////////////////////////////////////////////////////////////
// Name : 
// Desc : 
///////////////////////////////////////////////////////////////////////////////////////////////////////////
cTrayIcon::cTrayIcon(CWnd* pWnd, UINT uCallbackMessage, LPCTSTR szToolTip, 
					 HICON icon, UINT uID)
{
	create(pWnd, uCallbackMessage, szToolTip, icon, uID);
}


///////////////////////////////////////////////////////////////////////////////////////////////////////////
// Name : 
// Desc : 
///////////////////////////////////////////////////////////////////////////////////////////////////////////
BOOL cTrayIcon::create(CWnd* pWnd, UINT uCallbackMessage, LPCTSTR szToolTip, HICON icon, UINT uID)
{
	//Make sure we avoid conflict with other messages
	ASSERT(uCallbackMessage >= WM_USER);

	//Tray only supports tooltip text up to 64 characters
	ASSERT(_tcslen(szToolTip) <= 64);

	// NOTIFYICONDATA 구조체의 값 설정
	m_tnd.cbSize = sizeof(NOTIFYICONDATA);
	m_tnd.hWnd	 = pWnd->GetSafeHwnd();
	m_tnd.uID	 = uID;
	m_tnd.hIcon  = icon;
	m_tnd.uFlags = NIF_MESSAGE | NIF_ICON | NIF_TIP;
	m_tnd.uCallbackMessage = uCallbackMessage;
	_tcscpy_s(m_tnd.szTip, sizeof(m_tnd.szTip) / sizeof(TCHAR), szToolTip);
	
	// 트레이 아이콘 추가
	return Shell_NotifyIcon(NIM_ADD, &m_tnd);
}


///////////////////////////////////////////////////////////////////////////////////////////////////////////
// Name : 
// Desc : 
///////////////////////////////////////////////////////////////////////////////////////////////////////////
cTrayIcon::~cTrayIcon()
{
	removeIcon();
}


///////////////////////////////////////////////////////////////////////////////////////////////////////////
// Name : 
// Desc : 
///////////////////////////////////////////////////////////////////////////////////////////////////////////
void cTrayIcon::removeIcon()
{
	m_tnd.uFlags = 0;
    Shell_NotifyIcon(NIM_DELETE, &m_tnd);
	m_animateIconList.RemoveAll();
}


